#!/usr/bin/env python3
"""
gen_cmake_sources.py - emit the runtime's source list as CMake.

Phase 4.1. The Android app builds its native library with CMake, but the decision of
*which* sources belong in an Android build already exists, in compile_runtime.py:
two tables of exclusions (EXCLUDE_PLATFORM, EXCLUDE_DEFERRED) that took a phase of
work to get right, plus the scope definitions.

Rather than restate those as CMake regexes - a second copy to drift out of step - this
imports them and writes the answer out. compile_runtime.py stays the single source of
truth for what compiles.

The output is generated, not committed: it names absolute paths into
build/runtime-tree, which does not exist until assemble_runtime.py has run. CMake
regenerates it at configure time.

Usage:
  python tools/gen_cmake_sources.py --scope device
  python tools/gen_cmake_sources.py --scope device --out build/gen/runtime-sources.cmake
  python tools/gen_cmake_sources.py --scope device --list      # just print them
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import compile_runtime as cr  # noqa: E402  (needs the path set above)

DEFAULT_OUT = ROOT / "build" / "gen" / "runtime-sources.cmake"

# The recompiled title. ppc_tu6 is the Title Update build - see STATUS.md on TU6 vs
# TU7: the tu6 config handles TU7, whose code differs only in a version number.
GUEST_BUILD = "ppc_tu6"
GENERATED = ROOT / "recomp" / "generated"
# simde maps the x86 intrinsics XenonRecomp emits onto NEON. The generated units
# include <x86/sse.h> directly, so its parent has to be on the include path.
SIMDE = ROOT / "third_party" / "XenonRecomp" / "thirdparty" / "simde"


def cmake_path(p):
    """CMake wants forward slashes on every platform, including Windows."""
    return Path(p).as_posix()


def generate(scope):
    srcs, skipped = cr.sources(scope, only=None, apply_selection=True)
    if not srcs:
        raise SystemExit(
            f"error: no sources for scope '{scope}'.\n"
            f"       Is the tree assembled?  python tools/assemble_runtime.py")

    lines = [
        "# Generated by tools/gen_cmake_sources.py - do not edit.",
        f"# scope: {scope}",
        "#",
        "# The exclusions applied here live in tools/compile_runtime.py, which is the",
        "# single source of truth for what belongs in an Android build. Regenerate",
        "# rather than editing: this file is overwritten at CMake configure time.",
        "",
        "set(DAO_RUNTIME_SOURCES",
    ]
    lines += [f"    {cmake_path(s)}" for s in srcs]
    lines.append(")")
    lines.append("")

    # The include roots, for the same reason: compile_runtime.py already knows them.
    lines.append("set(DAO_RUNTIME_INCLUDES")
    lines += [f"    {cmake_path(i)}" for i in cr.INCLUDES]
    lines.append(")")
    lines.append("")
    lines.append(f"set(DAO_RUNTIME_SOURCE_COUNT {len(srcs)})")
    lines.append("")

    # The recompiled title. Separate from the runtime because it is compiled
    # differently - C++17 and -O2, matching exactly what Phase 2 differentially
    # tested, rather than whatever the build type would otherwise impose. Generated
    # code is not stepped through in a debugger, and a debug build of 265 MB of it
    # would be slow to produce and enormous to ship.
    guest_dir = GENERATED / GUEST_BUILD
    guest = sorted(guest_dir.glob("*.cpp")) if guest_dir.is_dir() else []
    lines.append("set(DAO_GUEST_SOURCES")
    lines += [f"    {cmake_path(s)}" for s in guest]
    lines.append(")")
    lines.append("")
    lines.append("set(DAO_GUEST_INCLUDES")
    lines.append(f"    {cmake_path(guest_dir)}")
    lines.append(f"    {cmake_path(SIMDE)}")
    lines.append(")")
    lines.append("")
    lines.append(f"set(DAO_GUEST_SOURCE_COUNT {len(guest)})")
    lines.append("")
    return "\n".join(lines), srcs, skipped, guest


def main():
    ap = argparse.ArgumentParser(description="Emit the runtime source list as CMake")
    ap.add_argument("--scope", default="device",
                    choices=sorted({"device", "vulkan", "android", "all"}),
                    help="which source set (default: device, the proven subset)")
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="output .cmake path")
    ap.add_argument("--list", action="store_true", help="print the sources, write nothing")
    a = ap.parse_args()

    text, srcs, skipped, guest = generate(a.scope)

    if a.list:
        for s in srcs:
            print(cmake_path(s))
        print(f"\n{len(srcs)} runtime sources, {len(skipped)} excluded, "
              f"{len(guest)} guest sources", file=sys.stderr)
        return 0

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    # Only rewrite on change, so CMake does not reconfigure on every build.
    if out.is_file() and out.read_text(encoding="utf-8") == text:
        print(f"  unchanged: {out.relative_to(ROOT)} "
              f"({len(srcs)} runtime + {len(guest)} guest sources)")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    platform = sum(1 for _p, _r, kind in skipped if kind == "platform")
    deferred = len(skipped) - platform
    print(f"  wrote {out.relative_to(ROOT)}: {len(srcs)} runtime sources "
          f"({platform} excluded as wrong-platform, {deferred} as deferred), "
          f"{len(guest)} guest sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
