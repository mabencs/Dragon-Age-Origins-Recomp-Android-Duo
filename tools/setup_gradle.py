#!/usr/bin/env python3
"""
setup_gradle.py - fetch Gradle so the Android app module can be built.

Phase 4.1. Gradle is not distributed through winget (checked: no package), and the
Android Gradle Plugin needs a Gradle of its own generation, so this pins one and
verifies it rather than leaving the version to whatever a machine happens to have.

Why this exists at all, when the repo has a Gradle *wrapper*: the wrapper is what
every other computer uses, and it downloads Gradle by itself. But the wrapper has to
be generated by a Gradle in the first place, and committing a `gradle-wrapper.jar`
without having run the Gradle that produced it would mean committing a binary blob on
trust. So: fetch a verified Gradle here, let it generate the wrapper, commit that.

After this, `gradlew` is the entry point and this script is not needed again unless
the pinned Gradle version changes.

  JDK: Gradle needs one. This project pins Temurin 17 (see docs/TOOLCHAIN.md). The
  script reads JAVA_HOME from the user environment if the current shell lacks it,
  which happens in any shell started before the variable was set.

Usage:
  python tools/setup_gradle.py
  python tools/setup_gradle.py --check          # report state, change nothing
  python tools/setup_gradle.py --wrapper        # also generate the Gradle wrapper
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from pathlib import Path

# Pinned. Gradle publishes a .sha256 beside every distribution; this is that value,
# fetched from services.gradle.org, not computed from our own download.
GRADLE_VERSION = "9.8.2"
GRADLE_URL = f"https://services.gradle.org/distributions/gradle-{GRADLE_VERSION}-bin.zip"
GRADLE_SHA256 = "21bd5da2de49b642904077f38c0efdc7778e92b3ed0889392dca61b97e389607"

ROOT = Path(__file__).resolve().parent.parent
TOOLCHAIN = ROOT / "toolchain"
GRADLE_DIR = TOOLCHAIN / "gradle"
GRADLE_HOME = GRADLE_DIR / f"gradle-{GRADLE_VERSION}"
STAMP = GRADLE_DIR / "dao-gradle.txt"


def stamp_text():
    return f"gradle {GRADLE_VERSION}\n"


def launcher():
    """The Gradle entry script for this platform."""
    name = "gradle.bat" if os.name == "nt" else "gradle"
    return GRADLE_HOME / "bin" / name


def ready():
    return STAMP.is_file() and STAMP.read_text() == stamp_text() and launcher().is_file()


def java_home():
    """JAVA_HOME, falling back to the user-scope value on Windows.

    A shell started before the variable was set at user scope does not inherit it,
    which looks exactly like "no JDK installed" and is not.
    """
    value = os.environ.get("JAVA_HOME")
    if value and Path(value, "bin").is_dir():
        return Path(value)
    if os.name == "nt":
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
                value, _ = winreg.QueryValueEx(key, "JAVA_HOME")
            if value and Path(value, "bin").is_dir():
                return Path(value)
        except (ImportError, OSError):
            pass
    return None


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(url, dest):
    print(f"  downloading {url}")
    tmp = dest.with_suffix(dest.suffix + ".part")
    with urllib.request.urlopen(url, timeout=300) as r, open(tmp, "wb") as fh:
        shutil.copyfileobj(r, fh)
    tmp.replace(dest)
    return dest


def fetch():
    GRADLE_DIR.mkdir(parents=True, exist_ok=True)
    archive = GRADLE_DIR / f"gradle-{GRADLE_VERSION}-bin.zip"
    if not archive.is_file():
        download(GRADLE_URL, archive)

    digest = sha256(archive)
    if digest != GRADLE_SHA256:
        archive.unlink(missing_ok=True)
        raise SystemExit(
            f"error: gradle sha256 mismatch\n  got      {digest}\n  expected {GRADLE_SHA256}")
    print(f"  sha256 verified: {digest}")

    if GRADLE_HOME.is_dir():
        shutil.rmtree(GRADLE_HOME)
    with zipfile.ZipFile(archive) as zf:
        zf.extractall(GRADLE_DIR)
    if not launcher().is_file():
        raise SystemExit(f"error: {launcher()} missing after extracting {archive}")

    if os.name != "nt":
        # ZipFile does not preserve the executable bit.
        for script in GRADLE_HOME.joinpath("bin").iterdir():
            script.chmod(script.stat().st_mode | 0o111)

    archive.unlink(missing_ok=True)
    STAMP.write_text(stamp_text())
    print(f"  extracted: {GRADLE_HOME}")


def run_gradle(args):
    jdk = java_home()
    if not jdk:
        raise SystemExit(
            "error: no JDK found. Set JAVA_HOME, or see docs/TOOLCHAIN.md.\n"
            "       This project pins Temurin 17.")
    env = dict(os.environ, JAVA_HOME=str(jdk))
    cmd = [str(launcher()), *args]
    print(f"  $ gradle {' '.join(args)}")
    return subprocess.run(cmd, cwd=ROOT, env=env).returncode


def make_wrapper():
    """Generate the committed wrapper, so other computers need only a JDK."""
    rc = run_gradle(["wrapper", "--gradle-version", GRADLE_VERSION,
                     "--distribution-type", "bin", "--quiet"])
    if rc != 0:
        raise SystemExit(f"error: `gradle wrapper` failed (exit {rc})")
    for f in ("gradlew", "gradlew.bat", "gradle/wrapper/gradle-wrapper.properties",
              "gradle/wrapper/gradle-wrapper.jar"):
        mark = "yes" if (ROOT / f).is_file() else "MISSING"
        print(f"  {f:<44} {mark}")


def report():
    jdk = java_home()
    print("gradle state")
    print(f"  pinned        {stamp_text().strip()}")
    print(f"  home          {GRADLE_HOME}")
    print(f"  ready         {'yes' if ready() else 'no'}")
    print(f"  JAVA_HOME     {jdk if jdk else 'NOT FOUND'}")
    wrapper = ROOT / "gradlew.bat" if os.name == "nt" else ROOT / "gradlew"
    print(f"  wrapper       {'yes' if wrapper.is_file() else 'no'}  ({wrapper.name})")
    return 0 if ready() else 1


def main():
    ap = argparse.ArgumentParser(description="Fetch a pinned Gradle for the app module")
    ap.add_argument("--check", action="store_true", help="report state and exit")
    ap.add_argument("--wrapper", action="store_true",
                    help="also generate the committed Gradle wrapper")
    a = ap.parse_args()

    if a.check:
        return report()

    if ready():
        print(f"already set up: {stamp_text().strip()}")
        print(f"  {GRADLE_HOME}")
    else:
        fetch()

    if a.wrapper:
        make_wrapper()

    print()
    print("Use the wrapper from here on:  ./gradlew :app:assembleDebug")
    return 0


if __name__ == "__main__":
    sys.exit(main())
