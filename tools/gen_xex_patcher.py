#!/usr/bin/env python3
"""
gen_xex_patcher.py - XenonRecomp's XEX patcher, trimmed for Android.

Task 5.0f. `XexPatcher::apply(bytes...)` is what produced recomp/generated/ppc_tu6, so
the app uses it rather than a reimplementation: a patched image assembled any other way
could disagree with the code that was translated from it.

The bytes-in/bytes-out overload is portable. The *path*-based one next to it is not - it
uses `MemoryMappedFile`, which is a Win32 wrapper, and `std::ofstream`. Nothing here
calls it, so it is removed rather than ported, along with its include.

Two asserted find/replace edits, the same discipline as tools/assemble_runtime.py: if
upstream changes this file, the edit fails loudly instead of silently producing
something different.

Usage:
  python tools/gen_xex_patcher.py
  python tools/gen_xex_patcher.py --check
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "third_party" / "XenonRecomp" / "XenonUtils" / "xex_patcher.cpp"
DEFAULT_OUT = ROOT / "build" / "gen" / "xex_patcher_android.cpp"

HEADER = """// Generated by tools/gen_xex_patcher.py from
// third_party/XenonRecomp/XenonUtils/xex_patcher.cpp - do not edit.
//
// The path-based XexPatcher::apply overload is removed: it uses MemoryMappedFile, a
// Win32 wrapper, and nothing in this app calls it. The bytes-in/bytes-out overload,
// which is the one used, is untouched.
"""

EDITS = [
    ("drop the memory_mapped_file include",
     '#include "memory_mapped_file.h"\n',
     "// DAO: removed - Win32-only, and only the path-based overload used it.\n"),
    ("drop the path-based apply overload",
     "XexPatcher::Result XexPatcher::apply(const std::filesystem::path &baseXexPath, "
     "const std::filesystem::path &patchXexPath, const std::filesystem::path "
     "&newXexPath)\n{",
     "// DAO: the path-based overload is removed; it needs MemoryMappedFile and\n"
     "// std::ofstream, and nothing in the app calls it.\n"
     "#if 0\n"
     "XexPatcher::Result XexPatcher::apply(const std::filesystem::path &baseXexPath, "
     "const std::filesystem::path &patchXexPath, const std::filesystem::path "
     "&newXexPath)\n{"),
    # BUG-046. A delta patch "move" copies a block to a new address inside the same
    # image, and the two ranges overlap whenever the block moves by less than its own
    # length. memcpy on overlapping ranges is undefined: the x64 host's C library
    # happens to copy it correctly (which is how recomp/generated/ppc_tu6 was made),
    # bionic's ARM64 memcpy copies forward and smears the block - Title Update 7 moves
    # ~27 KB of read-only data up by 0x1048 and the device got the start of it
    # repeated, so the module's script names, the event names and more read as
    # fragments of creature names, and "New Game" skipped the intro and character
    # creation. memmove is what the copy means.
    ("delta patch moves: memmove, the ranges overlap",
     "            std::memcpy(&dstData[curPatch->newAddress], &dstData[curPatch->oldAddress], "
     "curPatch->uncompressedLength);\n",
     "            // DAO (BUG-046): memmove - the ranges can overlap.\n"
     "            std::memmove(&dstData[curPatch->newAddress], &dstData[curPatch->oldAddress], "
     "curPatch->uncompressedLength);\n"),
    ("header delta: memmove, the ranges overlap",
     "        memcpy(&outBytes[patchDescriptor->deltaHeadersTargetOffset], "
     "&outBytes[patchDescriptor->deltaHeadersSourceOffset], "
     "patchDescriptor->deltaHeadersSourceSize);\n",
     "        // DAO (BUG-046): memmove - the ranges can overlap.\n"
     "        memmove(&outBytes[patchDescriptor->deltaHeadersTargetOffset], "
     "&outBytes[patchDescriptor->deltaHeadersSourceOffset], "
     "patchDescriptor->deltaHeadersSourceSize);\n"),
]


def generate():
    if not SOURCE.is_file():
        raise SystemExit(f"error: {SOURCE} not found; see THIRD_PARTY.md")
    text = SOURCE.read_text(encoding="utf-8", errors="replace")
    applied = []
    for description, find, replace in EDITS:
        count = text.count(find)
        if count != 1:
            raise SystemExit(
                f"error: edit '{description}' matched {count} times, expected 1.\n"
                f"       Upstream xex_patcher.cpp has changed - read the edit before\n"
                f"       changing it.")
        text = text.replace(find, replace)
        applied.append(description)
    # Close the #if 0 that swallowed the removed overload. It is the last function in
    # the file, so the guard runs to the end.
    text = text.rstrip() + "\n#endif  // DAO: path-based overload\n"
    return HEADER + text, applied


def main():
    ap = argparse.ArgumentParser(description="Trim XenonRecomp's XEX patcher for Android")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check", action="store_true", help="verify the edits, write nothing")
    a = ap.parse_args()

    text, applied = generate()
    for description in applied:
        print(f"  [ OK ] {description}")
    if a.check:
        print("\nall edits apply cleanly; nothing written (--check)")
        return 0

    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.is_file() and out.read_text(encoding="utf-8") == text:
        print(f"  unchanged: {out.relative_to(ROOT)}")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"  wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
