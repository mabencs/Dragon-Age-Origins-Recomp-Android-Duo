#!/usr/bin/env python3
"""
gen_gamecode_recipe.py - how the game's code is made into its library (PLAN 12.2).

The game's code - XenonRecomp's translation of the player's executable - is a library of
its own, libdaogame.so, made on the device by the app from the player's disc (PLAN 12.5)
or on the computer while developing (the `daogame` target, app/src/main/cpp/
CMakeLists.txt). Both make it the same way, from what this writes (committed, in the
APK's assets):

  app/src/main/assets/gamecode/hooks.h      force-included into every file of the game's
                                            code: its config and context headers, with
                                            the runtime's hooks around them
  app/src/main/assets/gamecode/shim.cpp     compiled with it: which runtime it was made
                                            for (the ABI), the image's layout, and a
                                            forwarder for each of the runtime's overrides
  app/src/main/assets/gamecode/recipe.json  the ABI, the compile and link flags, the
                                            overrides
  app/src/main/cpp/warden_gamecode_abi.h    the ABI the runtime loads (warden_game_library.cc)

The overrides are read from the runtime's sources: each WARDEN_OVERRIDE(tu6_sub_X) in
app/src/main/cpp. The ABI is a hash of everything above, so the runtime refuses game code
made for another version of it - the app then makes it again.

    python tools/gen_gamecode_recipe.py            write what changed
    python tools/gen_gamecode_recipe.py --check    exit 1 if a committed file is stale
    python tools/gen_gamecode_recipe.py --sources 7 recomp/generated/ppc_tu6
                                                   record the generated files' SHA-256s
                                                   for that title update (6 or 7) in
                                                   app/src/main/assets/gamecode/sources.json
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CPP = ROOT / "app" / "src" / "main" / "cpp"
ASSETS = ROOT / "app" / "src" / "main" / "assets" / "gamecode"
ABI_HEADER = CPP / "warden_gamecode_abi.h"

HOOKS = """// Generated by tools/gen_gamecode_recipe.py - do not edit (PLAN 12.2).
//
// Force-included into every file of the game's code (libdaogame.so), on the device as on
// the computer: the generated code's own config and context headers, with the hooks the
// runtime (libwarden.so) needs defined around them.
#include <cstdint>
#include "ppc_config.h"
// Memory-mapped stores (eieio-fenced) into the GPU register window: the ring buffer's
// write pointer above all, forwarded to warden_gpu.cc as DAORecomp's mmio_hook.h does.
extern "C" void warden_gpu_register_write(uint32_t address, uint32_t value);
#define PPC_MM_STORE_U32(x, y) do { const uint32_t warden_mm_address_ = (x); const uint32_t warden_mm_value_ = (y); PPC_STORE_U32(warden_mm_address_, warden_mm_value_); if ((warden_mm_address_ & 0xFFFF0000u) == 0x7FC80000u) warden_gpu_register_write(warden_mm_address_, warden_mm_value_); } while (0)
#include "ppc_context.h"
// The prologue records the function entered (warden_trace.cc): the fault report's and the
// thread report's guest call chains.
#undef PPC_FUNC_PROLOGUE
extern "C" void warden_guest_trace(const char* function);
#define PPC_FUNC_PROLOGUE() warden_guest_trace(__func__); __builtin_assume(((size_t)base & 0x1F) == 0)
"""

# The flags warden_guest was compiled with since Phase 2 (C++17, -O2, no debug info,
# warnings off), with the NDK's own for Android - what compile_commands.json shows for a
# guest unit, the later of each pair winning. {sysroot}, {resource_dir} and {include}
# are filled in by whoever compiles.
COMPILE = [
    "--target=aarch64-none-linux-android33",
    "--sysroot={sysroot}",
    "-resource-dir={resource_dir}",
    "-I{include}",
    "-I{simde}",
    "-DANDROID",
    "-fdata-sections",
    "-ffunction-sections",
    "-funwind-tables",
    "-fstack-protector-strong",
    "-no-canonical-prefixes",
    "-D_FORTIFY_SOURCE=2",
    "-frtti",
    "-fexceptions",
    "-fPIC",
    "-include{hooks}",
    "-std=c++17",
    "-O2",
    "-g0",
    "-w",
]

# ld.lld as the NDK's clang drives it for a shared library (clang -### shows it), with
# the game library's own: its name, its calls bound inside it (-Bsymbolic: the game's
# calls to its own functions direct, and to the runtime's overrides through shim.cpp's
# forwarders), and libwarden.so for what it calls in the runtime.
LINK = [
    "--sysroot={sysroot}",
    "-EL",
    "--fix-cortex-a53-843419",
    "-z", "now",
    "-z", "relro",
    "-z", "max-page-size=16384",
    "--hash-style=gnu",
    "--eh-frame-hdr",
    "-m", "aarch64linux",
    "-shared",
    "-soname", "libdaogame.so",
    "-Bsymbolic",
    "--build-id=sha1",
    "--no-undefined",
    "-o", "{output}",
    "{lib}/crtbegin_so.o",
    "-L{lib}",
    "{objects}",
    "{libwarden}",
    "-lm",
    "{builtins}",
    "{unwind}",
    "-ldl",
    "-lc",
    "{builtins}",
    "{unwind}",
    "-ldl",
    "{lib}/crtend_so.o",
]


def overrides():
    """Each WARDEN_OVERRIDE(tu6_sub_X) in the runtime's sources, and each one a macro
    makes - `#define NAME(address) ... WARDEN_OVERRIDE(tu6_sub_##address)`, at each
    NAME(XXXXXXXX) - sorted. The runtime checks the list as it loads the game's code
    (warden_game_library.cc), so one this misses is caught there."""
    texts = [path.read_text(encoding="utf-8") for path in sorted(CPP.glob("*.cc"))]
    found = set()
    macros = set()
    for text in texts:
        found.update(re.findall(r"^WARDEN_OVERRIDE\((tu6_sub_[0-9A-F]{8})\)", text, flags=re.M))
        for m in re.finditer(r"^#define[ \t]+(\w+)\(address\)((?:[^\n]*\\\n)*[^\n]*)", text,
                             flags=re.M):
            if "WARDEN_OVERRIDE(tu6_sub_##address)" in m.group(2):
                macros.add(m.group(1))
    for text in texts:
        for macro in macros:
            found.update("tu6_sub_" + address for address in
                         re.findall(r"^[ \t]*%s\(([0-9A-F]{8})\)" % macro, text, flags=re.M))
    return sorted(found)


def abi_of(names):
    digest = hashlib.sha256()
    for part in [HOOKS, "\n".join(names), "\n".join(COMPILE), "\n".join(LINK), "v1"]:
        digest.update(part.encode("utf-8"))
        digest.update(b"\0")
    return digest.hexdigest()[:16]


def shim(names, abi):
    lines = [
        "// Generated by tools/gen_gamecode_recipe.py - do not edit (PLAN 12.2).",
        "//",
        "// Compiled into the game's code (libdaogame.so) with it, on the device as on the",
        "// computer, with hooks.h force-included: what the runtime (libwarden.so) looks for",
        "// in it as it loads it (warden_game_library.cc), and a forwarder for each of the",
        "// runtime's overrides - the game's own calls and its function table reach them",
        "// through these.",
        "#include <cstdint>",
        "",
        "// The runtime this game code was made for; the runtime loads only its own.",
        'extern "C" __attribute__((visibility("default"))) const char warden_gamecode_abi[] = "%s";'
        % abi,
        "",
        "// The image's layout as it was translated - the title update decides its size, and",
        "// the indirect-call table sits right after it.",
        'extern "C" __attribute__((visibility("default"))) const uint64_t warden_gamecode_config[4] = {',
        "    PPC_IMAGE_BASE, PPC_IMAGE_SIZE, PPC_CODE_BASE, PPC_CODE_SIZE};",
        "",
        "// The overrides forwarded below, for the runtime to check against its own.",
        'extern "C" __attribute__((visibility("default"))) const char* const warden_gamecode_overrides[] = {',
    ]
    lines += ['    "%s",' % name for name in names]
    lines += [
        "    nullptr};",
        "",
        "// The runtime's overrides (WARDEN_OVERRIDE in app/src/main/cpp).",
    ]
    for name in names:
        lines.append('extern "C" PPC_FUNC(warden_override_%s);' % name)
    lines.append("")
    for name in names:
        lines.append("PPC_FUNC(%s) { warden_override_%s(ctx, base); }" % (name, name))
    return "\n".join(lines) + "\n"


def recipe(names, abi):
    return json.dumps({
        "comment": "Generated by tools/gen_gamecode_recipe.py - do not edit (PLAN 12.2).",
        "abi": abi,
        "compile": COMPILE,
        "link": LINK,
        "overrides": names,
    }, indent=1) + "\n"


def abi_header(abi):
    return ("// Generated by tools/gen_gamecode_recipe.py - do not edit (PLAN 12.2).\n"
            "//\n"
            "// The game code this runtime loads: made with app/src/main/assets/gamecode/'s\n"
            "// hooks.h, shim.cpp and recipe.json as they are now.\n"
            "#pragma once\n"
            "#define WARDEN_GAMECODE_ABI \"%s\"\n" % abi)


def outputs():
    names = overrides()
    abi = abi_of(names)
    return {
        ASSETS / "hooks.h": HOOKS,
        ASSETS / "shim.cpp": shim(names, abi),
        ASSETS / "recipe.json": recipe(names, abi),
        ABI_HEADER: abi_header(abi),
    }, names, abi


def record_sources(tu, folder):
    folder = Path(folder)
    files = sorted(list(folder.glob("*.cpp")) + list(folder.glob("*.h")))
    if not files:
        raise SystemExit("no generated files in %s" % folder)
    path = ASSETS / "sources.json"
    data = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {
        "comment": "Generated by tools/gen_gamecode_recipe.py --sources: the SHA-256 of each "
                   "file XenonRecomp makes from the disc's executable with that title update "
                   "(PLAN 12.4) - the device checks its own against these.",
        "tu": {}}
    data["tu"][str(tu)] = {f.name: hashlib.sha256(f.read_bytes()).hexdigest() for f in files}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n", encoding="utf-8",
                    newline="\n")
    print("recorded %d files for Title Update %s in %s" % (len(files), tu,
                                                           path.relative_to(ROOT)))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--sources", nargs=2, metavar=("TU", "FOLDER"))
    args = parser.parse_args()
    if args.sources:
        record_sources(*args.sources)
        return 0
    files, names, abi = outputs()
    stale = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check:
        if stale:
            print("stale: %s - run python tools/gen_gamecode_recipe.py"
                  % ", ".join(str(p.relative_to(ROOT)) for p in stale))
            return 1
        print("game code recipe current: ABI %s, %d overrides" % (abi, len(names)))
        return 0
    print("game code recipe: ABI %s, %d overrides%s" % (
        abi, len(names), "; wrote " + ", ".join(p.name for p in stale) if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
