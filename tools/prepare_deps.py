#!/usr/bin/env python3
"""
prepare_deps.py - generate the third-party sources that no checkout provides.

Phase 3.2. Linking the runtime needs three things that are not in any repository,
because each is normally produced by a build system we are not running:

  snappy-stubs-public.h   snappy generates it from a .in template via CMake
  stb_impl.cc             stb is header-only; something must define its
                          IMPLEMENTATION macros, and in Xenia the only file that
                          does is imgui_drawer.cc, which the Android build excludes
  (fmt)                   needs no generation, only compiling - handled by
                          compile_runtime.py's THIRD_PARTY_SOURCES

Run this once after fetching the submodules, and again if they are re-fetched.

Usage:
  python tools/prepare_deps.py
  python tools/prepare_deps.py --check
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANARY_TP = ROOT / "third_party" / "xenia-canary" / "third_party"
SNAPPY = CANARY_TP / "snappy"
GEN = ROOT / "build" / "deps-gen"


def snappy_version():
    """Read the version out of snappy's own CMakeLists rather than hardcoding it."""
    text = (SNAPPY / "CMakeLists.txt").read_text(encoding="utf-8", errors="replace")
    m = re.search(r"project\(\s*Snappy\s+VERSION\s+(\d+)\.(\d+)\.(\d+)", text)
    if not m:
        return None
    return m.group(1), m.group(2), m.group(3)


def make_snappy_header(check):
    """Substitute snappy's template the way its CMake build would.

    Written next to snappy's own sources because they include it by plain name
    (#include "snappy-stubs-public.h"), so it has to sit beside them. The whole
    checkout is gitignored, and re-fetching simply means running this again.
    """
    template = SNAPPY / "snappy-stubs-public.h.in"
    out = SNAPPY / "snappy-stubs-public.h"
    if not template.is_file():
        return False, f"missing {template}"
    ver = snappy_version()
    if not ver:
        return False, "could not read snappy's version from its CMakeLists"

    text = template.read_text(encoding="utf-8", errors="replace")
    # Android's bionic provides sys/uio.h, so iovec comes from the system header
    # rather than snappy's own fallback definition.
    values = {
        "HAVE_SYS_UIO_H_01": "1",
        "PROJECT_VERSION_MAJOR": ver[0],
        "PROJECT_VERSION_MINOR": ver[1],
        "PROJECT_VERSION_PATCH": ver[2],
    }
    for key, value in values.items():
        text = text.replace("${%s}" % key, value)

    leftover = re.findall(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}", text)
    if leftover:
        return False, "unsubstituted placeholders: " + ", ".join(sorted(set(leftover)))

    if check:
        state = "present" if out.is_file() else "MISSING"
        return True, f"snappy {'.'.join(ver)} header {state}"
    out.write_text(text, encoding="utf-8", newline="\n")
    return True, f"wrote {out.relative_to(ROOT)} (snappy {'.'.join(ver)})"


STB_IMPL = """// Generated by tools/prepare_deps.py - do not edit.
//
// stb is header-only and needs exactly one translation unit to define its
// IMPLEMENTATION macros. In Xenia that unit is ui/imgui_drawer.cc, which the
// Android build excludes (it needs ImGui, deferred to Phase 10) - but
// base/png_utils.cc still calls stbi_*, so without this the link fails on
// stbi_info_from_file and friends.
#include <cstdlib>

#define STB_IMAGE_IMPLEMENTATION
#define STB_IMAGE_WRITE_IMPLEMENTATION
// Note: STBI_NO_STDIO must not be defined at all - stb tests it with
// #ifndef, so even defining it to 0 removes stbi_*_from_file, which
// base/png_utils.cc calls.
#include "third_party/stb/stb_image.h"
#include "third_party/stb/stb_image_write.h"
"""


def make_stb_impl(check):
    out = GEN / "stb_impl.cc"
    for header in ("stb_image.h", "stb_image_write.h"):
        if not (CANARY_TP / "stb" / header).is_file():
            return False, f"missing third_party/stb/{header}"
    if check:
        state = "present" if out.is_file() else "MISSING"
        return True, f"stb implementation unit {state}"
    GEN.mkdir(parents=True, exist_ok=True)
    out.write_text(STB_IMPL, encoding="utf-8", newline="\n")
    return True, f"wrote {out.relative_to(ROOT)}"


def main():
    ap = argparse.ArgumentParser(description="Generate third-party sources for linking")
    ap.add_argument("--check", action="store_true", help="report state, write nothing")
    a = ap.parse_args()

    if not CANARY_TP.is_dir():
        print(f"error: {CANARY_TP} not found; see THIRD_PARTY.md", file=sys.stderr)
        return 1

    ok = True
    for name, fn in (("snappy header", make_snappy_header), ("stb implementation", make_stb_impl)):
        good, message = fn(a.check)
        print(f"  [{' OK ' if good else 'FAIL'}] {name:<20} {message}")
        ok = ok and good
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
